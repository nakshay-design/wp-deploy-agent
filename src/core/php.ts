import { randomBytes } from 'node:crypto';
import type { AdminConfig, SettingsConfig } from './types';

/** Encode a JS string as a safe single-quoted PHP literal. */
export function phpString(value: string): string {
  return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

export function randomToken(bytes = 16): string {
  const chars = 'abcdefghijklmnopqrstuvwxyz0123456789';
  let out = '';
  for (const b of randomBytes(bytes)) out += chars[b % chars.length];
  return out;
}

export interface SetupScriptOptions {
  token: string;
  themeSlug?: string;
  settings?: SettingsConfig;
  admin?: AdminConfig;
}

/**
 * Builds the one-time PHP script that is dropped into the web root, called over
 * HTTPS, then deleted. It loads WordPress, activates the theme, applies options
 * and (optionally) ensures an administrator login.
 */
export function buildSetupScript(opts: SetupScriptOptions): string {
  const { token, themeSlug, settings = {}, admin } = opts;

  const lines: string[] = [];
  lines.push('<?php');
  lines.push('/**');
  lines.push(' * Generated by wp-deploy-agent. One-time use; delete immediately after running.');
  lines.push(' */');
  lines.push("header('Content-Type: application/json');");
  lines.push('');
  lines.push(`$TOKEN = ${phpString(token)};`);
  lines.push("if ( ! isset( $_GET['k'] ) || ! hash_equals( $TOKEN, (string) $_GET['k'] ) ) {");
  lines.push('    http_response_code( 403 );');
  lines.push("    echo json_encode( array( 'error' => 'forbidden' ) );");
  lines.push('    exit;');
  lines.push('}');
  lines.push('');
  lines.push("require __DIR__ . '/wp-load.php';");
  lines.push('');
  lines.push('$out = array();');
  lines.push("$out['was_theme'] = get_option( 'stylesheet' );");

  if (themeSlug) {
    lines.push('');
    lines.push(`switch_theme( ${phpString(themeSlug)} );`);
    lines.push("$out['theme'] = get_option( 'stylesheet' );");
    lines.push("$out['template'] = get_option( 'template' );");
    lines.push(`$out['theme_exists'] = wp_get_theme( ${phpString(themeSlug)} )->exists();`);
  }

  const settingKeys = Object.keys(settings) as (keyof SettingsConfig)[];
  if (settingKeys.length > 0) {
    lines.push('');
    lines.push('/* Core site options */');
    for (const key of settingKeys) {
      const value = settings[key];
      if (value === undefined || value === null) continue;
      const literal = typeof value === 'number' ? String(value) : phpString(String(value));
      lines.push(`update_option( ${phpString(key)}, ${literal} );`);
    }
  }

  if (admin?.login && admin?.password) {
    lines.push('');
    lines.push('/* Ensure a known administrator login */');
    lines.push(`$login = ${phpString(admin.login)};`);
    lines.push(`$pass  = ${phpString(admin.password)};`);
    lines.push(`$email = ${phpString(admin.email ?? `${admin.login}@example.com`)};`);
    lines.push("$user = get_user_by( 'login', $login );");
    lines.push('if ( $user ) {');
    lines.push('    wp_set_password( $pass, $user->ID );');
    lines.push('    $uid = $user->ID;');
    lines.push("    $out['admin_action'] = 'password_reset';");
    lines.push('} else {');
    lines.push('    $uid = wp_create_user( $login, $pass, $email );');
    lines.push("    $out['admin_action'] = is_wp_error( $uid ) ? 'error:' . $uid->get_error_message() : 'created';");
    lines.push('}');
    lines.push('if ( ! is_wp_error( $uid ) ) {');
    lines.push("    $u = new WP_User( $uid );");
    lines.push("    $u->set_role( 'administrator' );");
    lines.push("    $out['admin_login'] = $login;");
    lines.push('}');
    lines.push(
      "$admins = get_users( array( 'role' => 'administrator', 'fields' => array( 'user_login' ) ) );",
    );
    lines.push("$out['all_admins'] = wp_list_pluck( $admins, 'user_login' );");
  }

  lines.push('');
  lines.push('flush_rewrite_rules();');
  lines.push('');
  lines.push("$out['siteurl'] = get_option( 'siteurl' );");
  lines.push("$out['home']    = get_option( 'home' );");
  lines.push("$out['ok']      = true;");
  lines.push('');
  lines.push('echo json_encode( $out, JSON_PRETTY_PRINT );');

  return `${lines.join('\n')}\n`;
}

